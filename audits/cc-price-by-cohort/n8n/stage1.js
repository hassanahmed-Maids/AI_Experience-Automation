const parseCard = node({
  type: 'n8n-nodes-base.code',
  version: 2,
  config: {
    name: 'Parse + Assert Card',
    parameters: {
      jsCode: [
        '// PRICE CARD PARSER + CHECKSUM. Lifted verbatim from the proven throwaway',
        '// reader (1kX3isU27HfmPMU0), with the checksum promoted to a hard stop.',
        '// Column F ("Minimum monthly payment + VAT") is the comparison figure.',
        '// Column E is ex-VAT; comparing on it drops old-price agreement to 98.72%.',
        '// Parse BY HEADER NAME - the live-out Filipina 2025-09-15 row exports with',
        '// extra unlabelled cells appended, which shift positional parsing.',
        'const rows = [];',
        'for (const i of $input.all()) { rows.push(i.json); }',
        '',
        'function norm(s) { return String(s === undefined || s === null ? "" : s).trim(); }',
        '',
        'function bucketNationality(n) {',
        '  const v = norm(n).toLowerCase();',
        '  if (v === "filipina") return "Filipina";',
        '  if (v === "ethiopian") return "Ethiopian";',
        '  if (v === "") return null;',
        '  return "Other";',
        '}',
        '',
        'function liveOutOf(contractType) {',
        '  const v = norm(contractType).toLowerCase();',
        '  if (v.indexOf("live-out") !== -1 || v.indexOf("live out") !== -1) return true;',
        '  if (v.indexOf("live-in") !== -1 || v.indexOf("live in") !== -1) return false;',
        '  return null;',
        '}',
        '',
        'const windows = [];',
        'const rejected = [];',
        'for (const r of rows) {',
        '  const keys = Object.keys(r);',
        '  const get = function (want) {',
        '    for (const k of keys) { if (norm(k).toLowerCase() === want) { return r[k]; } }',
        '    return undefined;',
        '  };',
        '  const liveOut = liveOutOf(get("contract type"));',
        '  const bucket = bucketNationality(get("nationality"));',
        '  const start = get("start date");',
        '  const price = Number(get("minimum monthly payment + vat"));',
        '  if (liveOut === null || bucket === null || !isFinite(price) || price <= 0 || !norm(start)) {',
        '    rejected.push({ contract_type: norm(get("contract type")), nationality: norm(get("nationality")), start: norm(start) });',
        '    continue;',
        '  }',
        '  windows.push({',
        '    cohort: (liveOut ? "liveout" : "livein") + ":" + bucket,',
        '    live_out: liveOut, bucket: bucket,',
        '    start: norm(start), end: norm(get("end date")),',
        '    price_inc_vat: price,',
        '  });',
        '}',
        '',
        'const byCohort = {};',
        'for (const w of windows) { if (!byCohort[w.cohort]) byCohort[w.cohort] = 0; byCohort[w.cohort]++; }',
        'const cohortCount = Object.keys(byCohort).length;',
        '',
        '// HARD STOP: exactly 49 windows across exactly 5 cohorts. If the file changed',
        '// shape the run stops rather than auditing everyone against a partial card.',
        '// A silently-changed reference file scores every contract wrongly with no error.',
        'const checksumOk = windows.length === 49 && cohortCount === 5;',
        'if (!checksumOk) {',
        '  throw new Error(',
        '    "PRICE CARD CHECKSUM FAILED: expected 49 windows across 5 cohorts, got " +',
        '    windows.length + " windows across " + cohortCount + " cohorts. Run stopped; " +',
        '    "no contract was scored. Rejected rows: " + rejected.length',
        '  );',
        '}',
        '',
        'const params = $("Validate Inputs").first().json.params;',
        'return [{ json: {',
        '  params: params,',
        '  price_card: {',
        '    windows: windows,',
        '    rows_read: rows.length,',
        '    windows_parsed: windows.length,',
        '    cohorts: cohortCount,',
        '    checksum_ok: true,',
        '    rejected_rows: rejected.length,',
        '  },',
        '} }];',
      ].join('\n'),
    },
  },
});

