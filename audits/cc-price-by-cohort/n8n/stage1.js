const validateInputs = node({
  type: 'n8n-nodes-base.code',
  version: 2,
  config: {
    name: 'Validate Inputs',
    parameters: {
      jsCode: [
        '// The ERP bearer is taken PER RUN from the payload. It is never stored in a',
        '// credential, never written to a Data Table, and never echoed into output -',
        '// it is the audit-trail attribution for every read this run makes.',
        'const raw = $input.first().json || {};',
        'const body = raw.body || raw;',
        'const auth = body.erp_auth || {};',
        'const errors = [];',
        '',
        'const bearer = String(auth.bearer || "").trim();',
        'const deviceId = String(auth.device_id || "").trim();',
        'if (!/^Bearer\\s+\\S+/.test(bearer)) errors.push("erp_auth.bearer missing or not a Bearer token");',
        'if (!/^\\d+$/.test(deviceId)) errors.push("erp_auth.device_id missing or not numeric");',
        '',
        '// The device id must belong to the same session as the bearer. A mismatched',
        '// pair authenticates inconsistently and, worse, usually means the token came',
        '// from someone else. Checked here rather than discovered mid-run.',
        'let tokenUser = null;',
        'if (errors.length === 0) {',
        '  try {',
        '    const seg = bearer.replace(/^Bearer\\s+/, "").split(".")[1];',
        '    const claims = JSON.parse(Buffer.from(seg, "base64").toString("utf8"));',
        '    tokenUser = claims.user || null;',
        '    if (claims.device && String(claims.device) !== deviceId) {',
        '      errors.push("erp_auth.device_id does not match the device claim inside the bearer");',
        '    }',
        '    if (claims.exp && Number(claims.exp) * 1000 < Date.now()) {',
        '      errors.push("bearer has already expired - ERP tokens last ~24h, get a fresh one");',
        '    }',
        '  } catch (e) {',
        '    errors.push("bearer is not a decodable JWT");',
        '  }',
        '}',
        '',
        'const p = body.params || {};',
        'const runId = String(p.run_id || ("run-" + new Date().toISOString().replace(/[^0-9]/g, "").slice(0, 14)));',
        'const smoke = p.smoke === true;',
        '',
        'return [{ json: {',
        '  ok: errors.length === 0,',
        '  errors: errors,',
        '  params: {',
        '    run_id: runId,',
        '    check_id: (smoke ? "SMOKE-" : "") + "manual-cc-price-by-cohort",',
        '    check_name: "CC Client Paying According to Price by Type / Nationality / Start Date",',
        '    smoke: smoke,',
        '    started_at: new Date().toISOString(),',
        '    // Population guard, build-handover s9 q1. Warn-only was requested but the',
        '    // Skeleton Contract mandates an abort floor, so the band version is built',
        '    // and is trivially switchable via the payload.',
        '    population: {',
        '      abort_below: Number(p.abort_below === undefined ? 4600 : p.abort_below),',
        '      warn_below: Number(p.warn_below === undefined ? 4900 : p.warn_below),',
        '      max_divergence_pct: Number(p.max_divergence_pct === undefined ? 1 : p.max_divergence_pct),',
        '      warn_only: p.warn_only === true,',
        '    },',
        '    erp_auth: {',
        '      bearer: bearer,',
        '      token_bare: bearer.replace(/^Bearer\\s+/, ""),',
        '      device_id: deviceId,',
        '      // Recorded so every finding can be traced to the identity that read it.',
        '      acting_user: tokenUser,',
        '    },',
        '  },',
        '} }];',
      ].join('\n'),
    },
  },
});

