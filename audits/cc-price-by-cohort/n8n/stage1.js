const populationGuard = node({
  type: 'n8n-nodes-base.code',
  version: 2,
  config: {
    name: 'Population Guard',
    parameters: {
      jsCode: [
        '// POPULATION COMPLETENESS (build-handover s9 q1).',
        '// A short pull produces a smaller, cleaner-looking report that is',
        '// indistinguishable from a genuinely clean month. That is the failure this',
        '// gate exists to catch, so it aborts rather than warns by default.',
        'const params = $("Parse + Assert Card").first().json.params;',
        'const card = $("Parse + Assert Card").first().json.price_card;',
        'const cfg = params.population;',
        '',
        'const rows = [];',
        'let reportedTotal = null;',
        'for (const item of $input.all()) {',
        '  const b = item.json || {};',
        '  const page = (b.clients && Array.isArray(b.clients.content)) ? b.clients.content : [];',
        '  for (const r of page) { rows.push(r); }',
        '  // `total` is available on this route - the handover\'s "no total, empty-page',
        '  // terminator only" applies to the dynamic-API pull, not to this one.',
        '  if (reportedTotal === null && b.total !== undefined && b.total !== null) reportedTotal = Number(b.total);',
        '}',
        '',
        '// De-duplicate on contract id. Aggregates on ERP endpoints have been measured',
        '// wrong by joins fanning rows out, so the de-duped count is the real one and',
        '// `total` is only the independent cross-check.',
        'const seen = {};',
        'const contracts = [];',
        'let dupes = 0;',
        'for (const r of rows) {',
        '  const id = String(r.contractId || r.id || r.contract_id || "");',
        '  if (!id) continue;',
        '  if (seen[id]) { dupes++; continue; }',
        '  seen[id] = true;',
        '  contracts.push(r);',
        '}',
        '',
        'const count = contracts.length;',
        'const independent = reportedTotal;',
        'const delta = independent === null ? null : count - independent;',
        'const deltaPct = (independent === null || independent === 0) ? null : Math.abs(delta) / independent * 100;',
        '',
        'const problems = [];',
        'if (count < cfg.abort_below) problems.push("population " + count + " is below the abort floor " + cfg.abort_below);',
        'if (deltaPct !== null && deltaPct > cfg.max_divergence_pct) {',
        '  problems.push("population diverges from the independent count by " + deltaPct.toFixed(2) + "% (limit " + cfg.max_divergence_pct + "%)");',
        '}',
        '',
        'const warn = count >= cfg.abort_below && count < cfg.warn_below;',
        'const complete = problems.length === 0 && !warn;',
        '',
        'if (problems.length && !cfg.warn_only) {',
        '  throw new Error("POPULATION GUARD FAILED: " + problems.join("; ") + ". Run stopped; no contract was scored.");',
        '}',
        '',
        'return [{ json: {',
        '  params: params,',
        '  price_card: card,',
        '  population: {',
        '    count: count,',
        '    independent_count: independent,',
        '    delta: delta,',
        '    delta_pct: deltaPct,',
        '    duplicates_dropped: dupes,',
        '    complete: complete,',
        '    guard: problems.length ? "failed-warn-only" : (warn ? "warn-band" : "ok"),',
        '    guard_notes: problems.join("; "),',
        '    source: "contract/search/page",',
        '  },',
        '  contracts: contracts,',
        '} }];',
      ].join('\n'),
    },
  },
});

const assembleBaton = node({
  type: 'n8n-nodes-base.code',
  version: 2,
  config: {
    name: 'Assemble Baton',
    parameters: {
      jsCode: [
        '// Slim baton for Stage 2. Only the fields the cohort key and the gates need',
        '// travel onward - per-contract payloads across ~5,000 contracts would blow',
        '// the 100 MB retained-data line in a single execution, which is the whole',
        '// reason this check is a 3-stage chain.',
        'const src = $input.first().json;',
        'const slim = [];',
        'for (const c of src.contracts) {',
        '  slim.push({',
        '    contract_id: String(c.contractId || c.id || c.contract_id || ""),',
        '    client_id: String(c.clientId || (c.client && c.client.id) || ""),',
        '    // Cohort inputs are NOT carried inline by this route - Stage 2 enriches',
        '    // them per contract. Recorded as null rather than guessed.',
        '    maid_nationality: c.maidNationality === undefined ? null : c.maidNationality,',
        '    live_out: c.maidLiveOut === undefined ? null : c.maidLiveOut,',
        '    contract_start_date: c.startDate === undefined ? null : c.startDate,',
        '  });',
        '}',
        'return [{ json: {',
        '  params: src.params,',
        '  price_card: src.price_card,',
        '  population: src.population,',
        '  contracts: slim,',
        '} }];',
      ].join('\n'),
    },
  },
});

export default workflow('cc-price-by-cohort-stage1', 'CC Price by Cohort · 1-Score')
  .add(runTrigger)
  .to(validateInputs)
  .to(inputsOk
    .onTrue(respond200.to(readCard).to(parseCard).to(getContracts).to(populationGuard).to(assembleBaton))
    .onFalse(respond400));
